#!/usr/bin/env python3
"""Rasterise Natural Earth 1:110m land at 2° cell centres using only the standard library."""

import argparse
import base64
import json
import textwrap
from pathlib import Path
from urllib.request import urlopen

URL = (
    "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/"
    "geojson/ne_110m_land.geojson"
)
OUTPUT = (
    Path(__file__).resolve().parents[2]
    / "composeApp/src/commonMain/kotlin/ch/ciuin/app/globe/GlobeLand.kt"
)
ROWS, COLS = 90, 180


def ring_intersections(ring, lat):
    for (x1, y1), (x2, y2) in zip(ring, ring[1:]):
        # Count one edge at a shared vertex so an even/odd fill handles holes.
        if (y1 > lat) != (y2 > lat):
            yield x1 + (x2 - x1) * (lat - y1) / (y2 - y1)


def rasterise(geojson):
    polygons = []
    for feature in geojson["features"]:
        geometry = feature["geometry"]
        if geometry["type"] == "Polygon":
            polygons.append(geometry["coordinates"])
        elif geometry["type"] == "MultiPolygon":
            polygons.extend(geometry["coordinates"])
        else:
            raise ValueError(f"Unexpected geometry: {geometry['type']}")

    mask = bytearray((ROWS * COLS + 7) // 8)
    for row in range(ROWS):
        lat = -89 + 2 * row
        for polygon in polygons:
            crossings = sorted(x for ring in polygon for x in ring_intersections(ring, lat))
            for left, right in zip(crossings[::2], crossings[1::2]):
                for col in range(COLS):
                    if left <= -179 + 2 * col < right:
                        index = COLS * row + col
                        mask[index // 8] |= 1 << (index % 8)
    return base64.b64encode(mask).decode("ascii")


def render(mask):
    chunks = " +\n".join(f'    "{chunk}"' for chunk in textwrap.wrap(mask, 100))
    return f"""package ch.ciuin.app.globe

import kotlin.io.encoding.Base64

// Generated by data/scripts/build_globe_land.py from Natural Earth 1:110m land (public domain).
private const val LAND_MASK =
{chunks}

private val landBits by lazy {{ Base64.decode(LAND_MASK) }}

/** Uses the land classification at the centre of the containing 2° cell. */
fun isLand(lat: Double, lon: Double): Boolean {{
    if (lat !in -90.0..90.0 || !lon.isFinite()) return false
    val row = ((lat + 90.0) / 2.0).toInt().coerceAtMost({ROWS - 1})
    val col = ((wrapLongitude(lon) + 180.0) / 2.0).toInt().coerceAtMost({COLS - 1})
    val index = row * {COLS} + col
    return (landBits[index / 8].toInt() and (1 shl (index % 8))) != 0
}}
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, help="Use a local copy of the Natural Earth GeoJSON")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    if args.input:
        geojson = json.loads(args.input.read_bytes())
    else:
        with urlopen(URL, timeout=30) as response:
            geojson = json.load(response)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(rasterise(geojson)), encoding="utf-8")


if __name__ == "__main__":
    main()
