/*
 * Vector data for the sheep and the duck, copied path for path from the character SVGs on the
 * "Foundations" board in Paper. Each character is split into the parts that move (head, ears,
 * eyes, wool, legs, book, tail) so the renderers in this package can transform them on their own.
 *
 * Coordinates are in each drawing's own view box; colours are ARGB.
 */

/** A filled or stroked SVG path. Strokes have round caps, as every stroke in the drawings does. */
internal class ArtPath(
    val d: String,
    val fill: Long? = null,
    val stroke: Long? = null,
    val strokeWidth: Float = 0f,
) {
    /** Parsed once, on first draw. */
    val path: Path by lazy(LazyThreadSafetyMode.NONE) { PathParser().parsePathString(d).toPath() }
}

/** A filled ellipse, optionally rotated about its own centre. */
internal class ArtOval(
    val cx: Float,
    val cy: Float,
    val rx: Float,
    val ry: Float,
    val fill: Long,
    val rotation: Float = 0f,
)

